// Package gentest holds package-level invariants for the generated clients.
//
// These tests cannot live beside the code they check: docsync clears the
// generated package directories (miniprogram/, official/) before rewriting
// them, so anything placed there is deleted on the next regeneration.
package gentest

import (
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"testing"

	"github.com/go-sphere/weixin-api/miniprogram"
	"github.com/go-sphere/weixin-api/official"
)

func repoRoot(t *testing.T) string {
	t.Helper()
	root, err := filepath.Abs(filepath.Join("..", ".."))
	if err != nil {
		t.Fatal(err)
	}
	return root
}

// TestGeneratedPackagesAreSelfIdentifying checks the provenance header is
// present so nobody mistakes generated files for hand-written ones.
func TestGeneratedPackagesAreSelfIdentifying(t *testing.T) {
	for _, pkg := range []string{"miniprogram", "official"} {
		dir := filepath.Join(repoRoot(t), pkg)
		entries, err := os.ReadDir(dir)
		if err != nil {
			t.Fatal(err)
		}
		goFiles := 0
		for _, e := range entries {
			if e.IsDir() || !strings.HasSuffix(e.Name(), ".go") {
				continue
			}
			goFiles++
			src, err := os.ReadFile(filepath.Join(dir, e.Name()))
			if err != nil {
				t.Fatal(err)
			}
			if !strings.Contains(string(src), "Code generated by docsync") {
				t.Errorf("%s/%s lacks the generated-code header", pkg, e.Name())
			}
		}
		if goFiles == 0 {
			t.Errorf("%s has no Go files", pkg)
		}
	}
}

// TestEveryEndpointMethodIsDocumented asserts the generated methods carry a
// Reference doc link, keeping godoc useful for agents and humans.
func TestEveryEndpointMethodIsDocumented(t *testing.T) {
	files := map[string][]string{}
	files["miniprogram"] = generatedFiles(t, "miniprogram")
	files["official"] = generatedFiles(t, "official")

	methodRe := regexp.MustCompile(`(?s)((?:^//[^\n]*\n)+)func \(c \*Client\) ([A-Za-z0-9_]+)\(`)
	for pkg, paths := range files {
		for _, path := range paths {
			src, err := os.ReadFile(path)
			if err != nil {
				t.Fatal(err)
			}
			for _, m := range methodRe.FindAllStringSubmatch(string(src), -1) {
				doc, name := m[1], m[2]
				if !strings.Contains(doc, "Doc: https://developers.weixin.qq.com") {
					t.Errorf("%s: %s lacks a documentation link", pkg, name)
				}
			}
		}
	}
}

func generatedFiles(t *testing.T, pkg string) []string {
	t.Helper()
	dir := filepath.Join(repoRoot(t), pkg)
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	var out []string
	for _, e := range entries {
		if strings.HasSuffix(e.Name(), ".go") {
			out = append(out, filepath.Join(dir, e.Name()))
		}
	}
	return out
}

// assertClientTypes is the compile-time contract: New must keep returning the
// concrete platform client type, not a narrower interface.
func assertClientTypes(*miniprogram.Client, *official.Client) {}

// TestConstructorSurface checks the documented constructors exist, so the
// replacement keeps the entry points callers rely on.
func TestConstructorSurface(t *testing.T) {
	assertClientTypes(miniprogram.New(miniprogram.Config{}), official.New(official.Config{}))
	_ = miniprogram.NewClient(nil)
	_ = official.NewClient(nil)
	// WithCredentials lets one process serve several accounts.
	if got := miniprogram.New(miniprogram.Config{AppID: "a"}).WithCredentials("b", "c"); got == nil {
		t.Error("miniprogram WithCredentials returned nil")
	}
	if got := official.New(official.Config{AppID: "a"}).WithCredentials("b", "c"); got == nil {
		t.Error("official WithCredentials returned nil")
	}
	// The shared crypto and JS-SDK facilities are reachable from both packages.
	if _, err := miniprogram.NewMessageCrypto("t", "abcdefghijklmnopqrstuvwxyz0123456789ABCDEFG", "wx"); err != nil {
		t.Errorf("miniprogram crypto: %v", err)
	}
	if _, err := official.NewMessageCrypto("t", "abcdefghijklmnopqrstuvwxyz0123456789ABCDEFG", "wx"); err != nil {
		t.Errorf("official crypto: %v", err)
	}
}

// TestXPayEnumSurface pins the reviewed constants that cannot be generated.
func TestXPayEnumSurface(t *testing.T) {
	if miniprogram.XPayEnvSandbox != 1 || miniprogram.XPayEnvProduction != 0 {
		t.Error("XPayEnv values changed")
	}
	if miniprogram.XPayErrSignError != 268490003 {
		t.Errorf("XPayErrSignError = %d", miniprogram.XPayErrSignError)
	}
	if miniprogram.XPayOrderStatusDelivered != 4 {
		t.Errorf("XPayOrderStatusDelivered = %d", miniprogram.XPayOrderStatusDelivered)
	}
}
