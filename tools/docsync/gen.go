// docFieldWords splits a documented field name on separators and camelCase
// boundaries, so "phoneNumber" -> [phone Number] and "access_token" ->
// [access token].
func docFieldWords(name string) []string {
	var words []string
	for _, seg := range strings.FieldsFunc(name, func(r rune) bool {
		return r == '_' || r == '-' || r == '.' || r == '/' || r == ' '
	}) {
		words = append(words, splitCamel(seg)...)
	}
	return words
}

// splitCamel splits one segment at lower->upper boundaries and before the last
// capital of an acronym run ("phoneNumber" -> phone, Number; "AppID" ->
// App, ID; "HTTPServer" -> HTTP, Server).
func splitCamel(s string) []string {
	r := []rune(s)
	if len(r) == 0 {
		return nil
	}
	var words []string
	start := 0
	for i := 1; i < len(r); i++ {
		switch {
		case unicode.IsLower(r[i-1]) && unicode.IsUpper(r[i]):
			words = append(words, string(r[start:i]))
			start = i
		case unicode.IsUpper(r[i-1]) && unicode.IsUpper(r[i]) && i+1 < len(r) && unicode.IsLower(r[i+1]):
			words = append(words, string(r[start:i]))
			start = i
		}
	}
	return append(words, string(r[start:]))
}

// titleField converts one documented word to its exported Go spelling.
func titleField(w string) string {
	if canon, ok := wordInitialisms[strings.ToLower(w)]; ok {
		return canon
	}
	if w == "" {
		return w
	}
	r := []rune(w)
	r[0] = unicode.ToUpper(r[0])
	return string(r)
}

// goFieldName converts a documented parameter name into an exported Go field
// name, preserving the docs' own casing (phoneNumber -> PhoneNumber) and
// guaranteeing uniqueness within the struct.
func goFieldName(name string, used map[string]int) string {
	var parts []string
	for _, w := range docFieldWords(name) {
		parts = append(parts, titleField(w))
	}
	field := strings.Join(parts, "")
	if field == "" {
		field = "Field"
	}
	if unicode.IsDigit(rune(field[0])) {
		field = "F" + field
	}
	base := field
	if n := used[base]; n > 0 {
		field = fmt.Sprintf("%s%d", base, n+1)
	}
	used[base]++
	return field
}

func writeStruct(f *File, name string, op *Operation) {
	f.Comment(name + " carries the documented parameters of one API call.")
	f.Type().Id(name).StructFunc(func(g *Group) {
		used := make(map[string]int)
		// sessionKeyField carries the user session key for signed user-level
		// calls; it is a client-side input, never part of the payload.
		if op.Signing == SignPaySigSession {
			g.Comment(sessionKeyField + " is the user session_key used to compute the user-level signature. It is not sent in the body.")
			g.Id(sessionKeyField).String().Tag(map[string]string{"json": "-"})
		}
		for _, fl := range op.Query {
			if clientOwnedParams(op, fl.Name) {
				continue // supplied by the runtime, not by the caller
			}
			writeField(f, g, fl, used, fieldTag("query", fl, fl.Required), name)
		}
		for _, fl := range op.Body {
			writeField(f, g, fl, used, fieldTag("json", fl, fl.Required), name)
		}
	})
	f.Line()
}

func writeStructResponse(f *File, name string, fields []Field) {
	f.Comment(name + " mirrors the documented response payload. Fields the docs do")
	f.Comment("not tabulate are not present; extend the struct as needed.")
	f.Type().Id(name).StructFunc(func(g *Group) {
		used := make(map[string]int)
		for _, fl := range fields {
			writeField(f, g, fl, used, fieldTag("json", fl, fl.Required), name)
		}
		if len(fields) == 0 {
			g.Id("_").Struct()
		}
	})
	f.Line()
}

// fieldTag builds the struct tag for one field: documented required fields are
// always serialized (no omit option), so a required value that happens to be the
// zero value is still sent. Optional numeric and boolean fields carry omitzero,
// because their Go zero value is what "absent" means for them; strings, slices
// and nested objects keep omitempty, the option matching their empty-value
// semantics.
func fieldTag(kind string, f Field, required bool) map[string]string {
	if required {
		return map[string]string{kind: f.Name}
	}
	return map[string]string{kind: f.Name + "," + omitOption(f)}
}

// omitOption is the encoding/json omission option for an optional field.
func omitOption(f Field) string {
	switch f.Type {
	case "integer", "number", "boolean":
		return "omitzero"
	default:
		return "omitempty"
	}
}

func writeField(file *File, g *Group, f Field, used map[string]int, tags map[string]string, owner string) {
	field := goFieldName(f.Name, used)
	if f.Desc != "" {
		g.Comment(f.Desc)
	}
	if len(f.Fields) > 0 {
		// namespace nested types by owner so two APIs with same-named
		// fields never share (wrong) definitions
		nestedName := owner + field + "Object"
		writeNestedStruct(file, nestedName, f.Fields, owner)
		if f.Type == "array" {
			g.Id(field).Index().Op("*").Id(nestedName).Tag(tags)
		} else {
			g.Id(field).Op("*").Id(nestedName).Tag(tags)
		}
		return
	}
	g.Id(field).Add(goFieldType(f)).Tag(tags)
}

// writeNestedStruct emits a struct for an inline nested object definition.
// Nested member types are pointers so recursive/optional objects stay valid.
func writeNestedStruct(file *File, name string, fields []Field, owner string) {
	if generatedTypes[name] {
		return
	}
	generatedTypes[name] = true
	file.Comment(name + " is a documented nested object.")
	file.Type().Id(name).StructFunc(func(g *Group) {
		used := make(map[string]int)
		for _, fl := range fields {
			writeField(file, g, fl, used, fieldTag("json", fl, fl.Required), owner)
		}
	})
}

// goFieldType renders the Go type of a field, honouring the array element type
// recorded during extraction (a "numarray" becomes []int64, not []string).
func goFieldType(f Field) Code {
	if f.Type == "array" {
		switch f.ItemsType {
		case "integer":
			return Index().Int64()
		case "number":
			return Index().Float64()
		case "boolean":
			return Index().Bool()
		case "object":
			return Index().Map(String()).Any()
		default:
			return Index().String()
		}
	}
	return goType(f.Type)
}

func goType(t string) Code {
	switch t {
	case "integer":
		return Int64()
	case "number":
		return Float64()
	case "boolean":
		return Bool()
	case "array":
		return Index().String()
	case "object":
		return Map(String()).Any()
	default:
		return String()
	}
}

