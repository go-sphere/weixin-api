// Config configures a Client. Request assembly, credential and token handling,
// request signing and error classification all live in the shared core
// runtime; this platform client only holds the account configuration.
type Config struct {
	// AppID / AppSecret fetch and refresh access tokens automatically.
	AppID     string
	AppSecret string
	// AppKey is the 米大师 / 虚拟支付 signing key. Signed XPay endpoints
	// require it; a signed call fails fast when it is empty.
	AppKey string
	// Env is the Mini Program deployment environment; it is the default for
	// the subscribe-message miniprogram_state. Empty means core.MiniAppEnvRelease.
	Env core.MiniAppEnv
	// Token overrides the AppID/AppSecret flow: when set it is called for every
	// request and no token is cached or refreshed.
	Token func(ctx context.Context) (string, error)
	// Cache stores access tokens; nil creates an in-process memory cache.
	Cache core.Cache
	// Proxy is an optional HTTP(S) proxy URL for outbound requests.
	Proxy string
	// BaseURL overrides the API host (tests, gateways).
	BaseURL string
	// HTTPClient injects a custom HTTP client.
	HTTPClient *http.Client
}

// Client calls one WeChat platform's server APIs.
type Client struct {
	*core.EndpointClient
}

// New builds a client from cfg.
func New(cfg Config) *Client {
	return &Client{EndpointClient: core.NewEndpointClient(core.EndpointConfig{
		AppID:      cfg.AppID,
		AppSecret:  cfg.AppSecret,
		AppKey:     cfg.AppKey,
		Env:        cfg.Env,
		Token:      cfg.Token,
		Cache:      cfg.Cache,
		Proxy:      cfg.Proxy,
		BaseURL:    cfg.BaseURL,
		HTTPClient: cfg.HTTPClient,
	})}
}

// NewClient builds a client around an access-token provider (no automatic
// refresh); it is shorthand for New(Config{Token: token}).
func NewClient(token func(ctx context.Context) (string, error)) *Client {
	return New(Config{Token: token})
}

// WithCredentials derives a client for another account, sharing the token cache
// and HTTP client so one process can serve several accounts.
func (c *Client) WithCredentials(appID, appSecret string) *Client {
	return &Client{EndpointClient: c.EndpointClient.WithCredentials(appID, appSecret)}
}

