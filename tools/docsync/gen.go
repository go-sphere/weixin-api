// generateGoClient renders the extracted operations as a Go client package.
// Names come exclusively from the endpoint (path, slug) via the deterministic
// rules in assignOperationIDs — LLM output never reaches an identifier.
// Jennifer manages the imports and formatting; the output always compiles.
func generateGoClient(dir, pkgName string, ops []*Operation) error {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	// The generated package replaces the hand-written one entirely, so every
	// existing .go file is removed first: a stale file from a previous layout
	// would otherwise survive and either collide with a generated symbol or
	// silently keep dead code in the package.
	if err := clearGoFiles(dir); err != nil {
		return err
	}
	clear(generatedTypes)
	files := map[string]*File{}
	for _, op := range ops {
		cat := categoryOf(op)
		f, ok := files[cat]
		if !ok {
			f = newAPIFile(pkgName)
			files[cat] = f
		}
		writeOperation(f, op)
	}

	names := slices.Sorted(maps.Keys(files))
	runtime := strings.ReplaceAll(strings.ReplaceAll(runtimeClient, "Package wxapi", "Package "+pkgName), "package wxapi", "package "+pkgName)
	if err := writeFormatted(filepath.Join(dir, "client.go"), []byte(runtime)); err != nil {
		return err
	}
	// Static extras: API surface the documentation does not describe, kept as
	// hand-reviewed templates so it survives regeneration.
	if err := writeStaticExtras(dir, pkgName); err != nil {
		return err
	}
	for _, name := range names {
		var rendered strings.Builder
		if err := files[name].Render(&rendered); err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(dir, name+".go"), []byte(rendered.String()), 0o644); err != nil {
			return err
		}
	}
	return nil
}

// writeFormatted writes src through go/format so the emitted runtime file is
// always canonical Go.
func writeFormatted(target string, src []byte) error {
	formatted, err := format.Source(src)
	if err != nil {
		_ = os.WriteFile(target+".bad", src, 0o644) // debugging aid
		return fmt.Errorf("format %s: %w", filepath.Base(target), err)
	}
	return os.WriteFile(target, formatted, 0o644)
}

// clearGoFiles removes every .go file directly inside dir, so a regenerated
// package cannot keep stale files.
func clearGoFiles(dir string) error {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".go") {
			continue
		}
		if err := os.Remove(filepath.Join(dir, e.Name())); err != nil {
			return err
		}
	}
	return nil
}

// writeStaticExtras writes the reviewed templates holding API surface the
// documentation does not describe (currently the XPay enumerations).
func writeStaticExtras(dir, pkgName string) error {
	tpl, ok := staticExtras[pkgName]
	if !ok {
		return nil
	}
	for name, body := range tpl {
		src := strings.ReplaceAll(body, "{{PKG}}", pkgName)
		if err := writeFormatted(filepath.Join(dir, name+".go"), []byte(src)); err != nil {
			return err
		}
	}
	return nil
}

// categoryOf derives a stable file/category name from the doc page URL.
func categoryOf(op *Operation) string {
	p := strings.TrimPrefix(op.Page, "https://developers.weixin.qq.com")
	for _, prefix := range []string{
		"/miniprogram/dev/server/API/",
		"/doc/service/api/",
		"/doc/subscription/api/",
	} {
		if strings.HasPrefix(p, prefix) {
			rest := strings.TrimPrefix(p, prefix)
			rest = strings.TrimSuffix(rest, "index.html")
			rest = strings.TrimSuffix(rest, ".html")
			if first, _, _ := strings.Cut(strings.Trim(rest, "/"), "/"); first != "" {
				return sanitizeFileBase(first)
			}
		}
	}
	return "misc"
}

func sanitizeFileBase(s string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(s) {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9':
			b.WriteRune(r)
		default:
			b.WriteByte('_')
		}
	}
	out := b.String()
	if out == "" {
		return "misc"
	}
	if out[0] >= '0' && out[0] <= '9' {
		out = "n" + out
	}
	return out
}

// generatedTypes tracks nested struct names already emitted in this run.
var generatedTypes = map[string]bool{}

// coreImportPath is the shared runtime the generated endpoints delegate to.
const coreImportPath = "github.com/go-sphere/weixin-api/core"

var reservedNames = map[string]bool{
	"Client": true, "Config": true, "call": true, "NewClient": true,
}

// newAPIFile creates a generated source file with the provenance header.
func newAPIFile(pkgName string) *File {
	f := NewFile(pkgName)
	f.HeaderComment("Code generated by docsync from the official WeChat documentation. DO NOT EDIT.")
	f.HeaderComment("The API surface (names, request/response shapes) is derived deterministically")
	f.HeaderComment("from the endpoints; regenerate with \"make docs-sync\". If this file changes")
	f.HeaderComment("under you, the upstream documentation changed.")
	// Endpoint methods delegate to the shared runtime.
	f.ImportName(coreImportPath, "core")
	return f
}

func writeOperation(f *File, op *Operation) {
	if reservedNames[op.ID] {
		return
	}
	reqName := op.ID + "Request"
	errVar := writeErrCodes(f, op)

	// Signed endpoints compute their request signatures in the runtime from
	// Config.AppKey (and the request's session key).
	signing := op.Signing

	// Endpoints that do not take an access_token (appid+secret flows, token
	// acquisition itself) must not fetch or send one.
	needAuth := op.Auth

	f.Comment(fmt.Sprintf("%s %s (%s %s)", op.ID, op.Summary, op.Method, op.Path))
	f.Comment("Doc: " + op.Page)
	writeStruct(f, reqName, op)

	params := []Code{
		Id("ctx").Qual("context", "Context"),
		Id("req").Op("*").Id(reqName),
	}
	if op.Upload != nil {
		params = append(params, Id("file").Op("*").Qual(coreImportPath, "Upload"))
	}

	// A multipart upload endpoint takes the request struct plus the file part
	// and keeps the documented response shape (bytes when it streams media).
	if op.Upload != nil {
		if op.BinaryResponse {
			f.Func().Params(Id("c").Op("*").Id("Client")).Id(op.ID).Params(params...).
				Params(Index().Byte(), Error()).
				Block(Return(Qual(coreImportPath, "CallUpload").Call(
					Id("c").Dot("EndpointClient"), Id("ctx"), Lit(op.Path), Id("req"), Id("file"), errDocsArg(errVar), authArg(needAuth),
				)))
			return
		}
		writeStructResponse(f, op.ID+"Response", op.Response)
		f.Func().Params(Id("c").Op("*").Id("Client")).Id(op.ID).Params(params...).
			Params(Op("*").Id(op.ID+"Response"), Error()).
			Block(
				List(Id("data"), Err()).Op(":=").Qual(coreImportPath, "CallUpload").Call(
					Id("c").Dot("EndpointClient"), Id("ctx"), Lit(op.Path), Id("req"), Id("file"), errDocsArg(errVar), authArg(needAuth),
				),
				Return(Qual(coreImportPath, "Decode").Types(Id(op.ID+"Response")).Call(
					Id("ctx"), Lit(op.Method), Lit(op.Path), Id("data"), Err(),
				)),
			)
		return
	}

	if op.BinaryResponse {
		// success returns raw bytes; only failures come back as the JSON
		// errcode envelope, which surfaces as *APIError
		f.Func().Params(Id("c").Op("*").Id("Client")).Id(op.ID).Params(params...).
			Params(Index().Byte(), Error()).
			Block(Return(Qual(coreImportPath, "CallBinary").Call(
				Id("c").Dot("EndpointClient"), Id("ctx"), Lit(op.Method), Lit(op.Path), Id("req"), errDocsArg(errVar), authArg(needAuth), signArg(signing),
			)))
		return
	}

	respName := op.ID + "Response"
	writeStructResponse(f, respName, op.Response)

	f.Func().Params(Id("c").Op("*").Id("Client")).Id(op.ID).Params(params...).
		Params(Op("*").Id(respName), Error()).
		Block(append(envDefaults(op), Return(Qual(coreImportPath, "Call").Types(Id(respName)).Call(
			Id("c").Dot("EndpointClient"), Id("ctx"), Lit(op.Method), Lit(op.Path), Id("req"), errDocsArg(errVar), authArg(needAuth), signArg(signing),
		)))...)
}

// writeErrCodes emits the documented error-code table of an operation as a
// package-level map and returns its name ("" when the page documents none).
func writeErrCodes(f *File, op *Operation) string {
	if len(op.Errors) == 0 {
		return ""
	}
	dict := Dict{}
	seen := make(map[int]bool)
	for _, e := range op.Errors {
		code, err := strconv.Atoi(strings.TrimSpace(e.Code))
		if err != nil || seen[code] {
			continue
		}
		seen[code] = true
		dict[Lit(code)] = Values(Dict{
			Id("Desc"):     Lit(e.Desc),
			Id("Solution"): Lit(e.Solution),
		})
	}
	if len(dict) == 0 {
		return ""
	}
	name := lowerFirst(op.ID) + "ErrCodes"
	f.Var().Id(name).Op("=").Map(Int()).Add(Qual(coreImportPath, "ErrDoc")).Values(dict)
	return name
}

// envDefaults emits the statements filling environment-derived fields the
// caller left empty.
func envDefaults(op *Operation) []Code {
	field, ok := envDefaultPaths[op.Path]
	if !ok {
		return nil
	}
	return []Code{
		If(Id("req").Op("!=").Nil().Op("&&").Id("req").Dot(field).Op("==").Lit("")).Block(
			Id("req").Dot(field).Op("=").Id("c").Dot("Env").Call().Dot("SubscribeState").Call(),
		),
	}
}

// envDefaultPaths are endpoints whose documented miniprogram_state field the
// client fills from Config.Env when the caller leaves it empty. The rule is
// fixed (endpoint-based), not inferred.
var envDefaultPaths = map[string]string{
	"/cgi-bin/message/subscribe/send": "MiniprogramState",
}

// signArg renders the compile-time signing mode of an endpoint.
func signArg(mode string) Code {
	switch mode {
	case SignPaySig:
		return Qual(coreImportPath, "SignPaySig")
	case SignPaySigSession:
		return Qual(coreImportPath, "SignPaySigSession")
	default:
		return Qual(coreImportPath, "SignNone")
	}
}

// authArg renders the compile-time flag telling the runtime whether the
// endpoint takes an access_token (and therefore needs one fetched).
func authArg(needs bool) Code {
	if needs {
		return True()
	}
	return False()
}

func errDocsArg(name string) Code {
	if name == "" {
		return Nil()
	}
	return Id(name)
}

func lowerFirst(s string) string {
	if s == "" {
		return s
	}
	r := []rune(s)
	r[0] = unicode.ToLower(r[0])
	return string(r)
}

